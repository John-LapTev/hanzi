/* Модальные: перед ними подлежащее, после — сам глагол. Владелец споткнулся именно здесь
   («я умею немного говорить по-китайски» — что идёт первым?), 25.08.2026. */
const MODALS = new Set(['会', '能', '可以', '想', '要', '应该', '需要']);

/* Количество стоит не там, где в русском: «немного говорю» → «говорю немного китайского». */
const AMOUNTS = new Set(['一点儿', '一下', '一些', '很多', '两', '一共']);

/* Слова, у которых место в предложении не зависит от словаря: они и есть разметка фразы. */
