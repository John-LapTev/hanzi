/* ═══════════════════ SENTENCE-ORDER — почему слова стоят именно так ═══════════════════
   Слабое место владельца — не слова, а порядок. В упражнении он собирал фразу, видел
   «правильно вот так» и не понимал, почему именно так. Здесь фраза разбирается по ролям:
   кто → когда → где → что делает → что именно. Ровно то, чему учат уроки грамматики,
   только показано на его собственном ответе.

   Роли определяются по словарю: часть речи и тема у каждого слова уже есть, плюс списки
   служебных слов, у которых место в предложении жёсткое.                                */

