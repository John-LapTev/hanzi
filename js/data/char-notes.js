/** Знак → вид. Списки собраны по словарю: половинки — те, что не бывают словом сами по себе. */
export const CHAR_KIND_OF = {};

const assign = (kind, characters) => {
  Array.from(characters).forEach((character) => { CHAR_KIND_OF[character] = kind; });
};

// Записывают чужие названия по звуку
